local t = require("spec.support")
local util = require("loglens.util")

t.describe("util.trim", function()
  t.it("strips ASCII whitespace on both sides", function()
    t.eq(util.trim("  a b \t\r\n"), "a b")
    t.eq(util.trim("abc"), "abc")
    t.eq(util.trim("   "), "")
    t.eq(util.trim(""), "")
  end)

  t.it("is linear on pathological input", function()
    local nasty = string.rep("a ", 20000) .. "b" .. string.rep(" ", 20000)
    local started = os.clock()
    t.eq(#util.trim(nasty), 40001)
    t.lt(os.clock() - started, 0.5)
  end)
end)

t.describe("util.percent_decode", function()
  t.it("decodes valid escapes and leaves invalid ones alone", function()
    t.eq(util.percent_decode("a%20b%2Fc"), "a b/c")
    t.eq(util.percent_decode("100%"), "100%")
    t.eq(util.percent_decode("%zz%4"), "%zz%4")
    t.eq(util.percent_decode("a+b"), "a+b")
  end)
end)

t.describe("util.scrub_utf8", function()
  t.it("keeps valid UTF-8 and replaces invalid bytes", function()
    t.eq(util.scrub_utf8("héllo"), "héllo")
    t.eq(util.scrub_utf8("a\xffb"), "a\u{FFFD}b")
    t.eq(util.scrub_utf8("\xc3"), "\u{FFFD}")
    t.eq(util.scrub_utf8("x\x80\x80y", "?"), "x??y")
    t.eq(util.scrub_utf8(""), "")
  end)
end)

t.describe("util.display_width", function()
  t.it("counts columns", function()
    t.eq(util.display_width("abc"), 3)
    t.eq(util.display_width("h\u{e9}llo"), 5)
    t.eq(util.display_width("\u{65e5}\u{672c}"), 4)
    t.eq(util.display_width("e\u{301}"), 1)
    t.eq(util.display_width("\u{2588}\u{2588}"), 2)
  end)

  t.it("ignores ANSI escapes only in visible_width", function()
    local coloured = "\27[1;32mok\27[0m"
    t.eq(util.display_width(coloured), 13)
    t.eq(util.visible_width(coloured), 2)
    t.eq(util.strip_ansi(coloured), "ok")
  end)

  t.it("does not fail on invalid UTF-8", function()
    t.eq(util.display_width("a\xffb"), 3)
  end)
end)

t.describe("util.truncate / pad", function()
  t.it("truncates by columns with an ellipsis", function()
    t.eq(util.truncate("hello world", 20), "hello world")
    t.eq(util.truncate("hello world", 8), "hello w\u{2026}")
    t.eq(util.truncate("hello world", 8, "..."), "hello...")
    t.eq(util.truncate("\u{65e5}\u{672c}\u{8a9e}\u{30c6}", 5), "\u{65e5}\u{672c}\u{2026}")
    t.eq(util.truncate("abc", 0), "")
  end)

  t.it("pads by visible width", function()
    t.eq(util.pad_right("ab", 5), "ab   ")
    t.eq(util.pad_left("ab", 5), "   ab")
    t.eq(util.pad_right("abcdef", 3), "abcdef")
    t.eq(util.pad_left("\27[31mab\27[0m", 4), "  \27[31mab\27[0m")
  end)

  t.it("wraps words into lines of at most the given width", function()
    t.eq(util.wrap("the quick brown fox", 9), { "the quick", "brown fox" })
    t.eq(util.wrap("  spaced \t out\n words  ", 40), { "spaced out words" })
    t.eq(util.wrap("", 10), {})
    t.eq(util.wrap("abcdefghij kl", 5), { "abcd\u{2026}", "kl" }, "a long word is truncated")
    for width = 1, 30 do
      for _, line in ipairs(util.wrap("Every line was rejected. Check the format with --format combined|common|json|caddy.", width)) do
        t.ok(util.display_width(line) <= width, "line too wide at " .. width .. ": " .. line)
      end
    end
  end)
end)

t.describe("util.defang", function()
  t.it("passes plain printable text through", function()
    t.eq(util.defang("/index.html?a=1&b=2"), "/index.html?a=1&b=2")
    t.eq(util.defang("caf\u{e9} /\u{65e5}\u{672c}"), "caf\u{e9} /\u{65e5}\u{672c}")
  end)

  t.it("escapes terminal control sequences", function()
    local out = util.defang("a\27[31mred\27[0m\r\n\0\127")
    t.eq(out, "a\\x1B[31mred\\x1B[0m\\x0D\\x0A\\x00\\x7F")
    t.not_contains(out, "\27")
  end)

  t.it("neutralises markup, shell and JNDI payloads", function()
    t.eq(util.defang("<script>alert('x')</script>"), "%3Cscript%3Ealert(%27x%27)%3C/script%3E")
    t.eq(util.defang("${jndi:ldap://x/a}"), "%24%7Bjndi:ldap://x/a%7D")
    t.eq(util.defang("`id`; echo \"$(whoami)\" \\"), "%60id%60; echo %22%24(whoami)%22 %5C")
  end)

  t.it("escapes invalid UTF-8 and bidi/invisible code points", function()
    t.eq(util.defang("a\xffb"), "a\\xFFb")
    t.eq(util.defang("\xc3"), "\\xC3")
    t.eq(util.defang("x\u{202E}y"), "x\\u202Ey")
    t.eq(util.defang("x\u{200B}y\u{FEFF}"), "x\\u200By\\uFEFF")
    t.eq(util.defang("\u{9b}31m"), "\\u009B31m")
    t.eq(util.defang("a\u{E0041}b"), "a\\U000E0041b")
  end)

  t.it("truncates by columns without splitting an escape", function()
    t.eq(util.defang("abcdefghij", 6), "abcde\u{2026}")
    t.eq(util.defang("ab<cd", 4), "ab\u{2026}")
    t.eq(util.defang("ab<cd", 5), "ab\u{2026}")
    t.eq(util.defang("ab<cd", 6), "ab%3C\u{2026}")
    t.eq(util.defang("ab<cd", 7), "ab%3Ccd")
    t.eq(util.defang("a\xff\xc3\xa9\x80b"), "a\\xFF\u{e9}\\x80b")
    t.eq(util.defang("abcdef", 4, "..."), "a...")
    local long = string.rep("<", 5000)
    t.eq(util.defang(long, 10), "%3C%3C%3C\u{2026}")
    t.eq(util.defang("12:00\u{2192}13:00 plenty of text follows", 20), "12:00\u{2192}13:00 plenty \u{2026}")
    t.eq(util.defang("<a>bcdefghij", 8), "%3Ca%3E\u{2026}")
    t.eq(util.defang("ab<cdefgh", 9), "ab%3Ccde\u{2026}")
  end)

  t.it("always yields valid, control-free output for arbitrary bytes", function()
    local seed = 7
    for _ = 1, 200 do
      local bytes = {}
      for i = 1, 40 do
        seed = (seed * 1103515245 + 12345) % 2147483648
        bytes[i] = string.char((seed >> 8) % 256)
      end
      local out = util.defang(table.concat(bytes), 60)
      t.ok(utf8.len(out), "output must be valid UTF-8")
      t.is_nil(out:find("[%c]"), "output must not contain control bytes")
      t.lt(util.display_width(out), 61)
    end
  end)
end)

t.describe("util number formatting", function()
  t.it("groups thousands", function()
    t.eq(util.fmt_int(0), "0")
    t.eq(util.fmt_int(999), "999")
    t.eq(util.fmt_int(1000), "1,000")
    t.eq(util.fmt_int(1234567), "1,234,567")
    t.eq(util.fmt_int(-1234), "-1,234")
    t.eq(util.fmt_int(100000), "100,000")
    t.eq(util.fmt_int(2.6), "3")
  end)

  t.it("compacts large counts", function()
    t.eq(util.fmt_compact(9999), "9,999")
    t.eq(util.fmt_compact(12900), "12.9K")
    t.eq(util.fmt_compact(4200000), "4.2M")
    t.eq(util.fmt_compact(1100000000), "1.1B")
    t.eq(util.fmt_compact(20000), "20K")
    t.eq(util.fmt_compact(999999), "1M")
  end)

  t.it("formats bytes with a 1024 base", function()
    t.eq(util.fmt_bytes(0), "0 B")
    t.eq(util.fmt_bytes(512), "512 B")
    t.eq(util.fmt_bytes(1536), "1.5 KiB")
    t.eq(util.fmt_bytes(1024 * 1024 * 12.3), "12.3 MiB")
    t.eq(util.fmt_bytes(1024 ^ 3 * 3), "3.0 GiB")
    t.eq(util.fmt_bytes(1048575), "1.0 MiB")
  end)

  t.it("formats durations", function()
    t.eq(util.fmt_duration_ms(0.42), "0.4 ms")
    t.eq(util.fmt_duration_ms(820), "820 ms")
    t.eq(util.fmt_duration_ms(999.9), "1.0 s")
    t.eq(util.fmt_duration_ms(3200), "3.2 s")
    t.eq(util.fmt_duration_ms(125000), "2m 05s")
    t.eq(util.fmt_duration_ms(3780000), "1h 03m")
  end)

  t.it("formats percentages and rounds", function()
    t.eq(util.fmt_pct(0.1234), "12.3%")
    t.eq(util.fmt_pct(1), "100.0%")
    t.eq(util.fmt_pct(0.005, 2), "0.50%")
    t.eq(util.round(2.5), 3)
    t.eq(util.round(3.14159, 2), 3.14)
    t.eq(math.type(util.round(3.7)), "integer")
  end)
end)

t.describe("util.suggest", function()
  t.it("measures edit distance", function()
    t.eq(util.edit_distance("kitten", "sitting"), 3)
    t.eq(util.edit_distance("", "abc"), 3)
    t.eq(util.edit_distance("abc", "abc"), 0)
  end)

  t.it("suggests close matches only", function()
    local flags = { "--format", "--watch", "--width", "--top" }
    t.eq(util.suggest("--fromat", flags), "--format")
    t.eq(util.suggest("--wacth", flags), "--watch")
    t.is_nil(util.suggest("--zzzzzzzz", flags))
  end)
end)

t.describe("util.url_host", function()
  t.it("extracts lower-case hosts", function()
    t.eq(util.url_host("https://Example.COM/path?q=1"), "example.com")
    t.eq(util.url_host("http://user:pw@host.test:8080/x"), "host.test")
    t.eq(util.url_host("https://[2001:db8::1]:443/"), "2001:db8::1")
    t.eq(util.url_host("android-app://com.google.android.gm"), "com.google.android.gm")
  end)

  t.it("rejects non-URLs", function()
    t.is_nil(util.url_host("-"))
    t.is_nil(util.url_host(""))
    t.is_nil(util.url_host("example.com/path"))
    t.is_nil(util.url_host("http:///path"))
  end)
end)

t.describe("util robust statistics", function()
  t.it("computes medians", function()
    t.eq(util.median({}), 0)
    t.eq(util.median({ 3 }), 3)
    t.eq(util.median({ 5, 1, 3 }), 3)
    t.eq(util.median({ 4, 1, 3, 2 }), 2.5)
  end)

  t.it("returns a MAD based scale and falls back to mean deviation", function()
    local centre, scale = util.robust_scale({ 1, 2, 3, 4, 100 })
    t.eq(centre, 3)
    t.near(scale, 1.4826 * 1, 1e-9)
    local c2, s2 = util.robust_scale({ 0, 0, 0, 0, 10 })
    t.eq(c2, 0)
    t.near(s2, 1.253314 * 2, 1e-9)
    local c3, s3 = util.robust_scale({ 5, 5, 5 })
    t.eq(c3, 5)
    t.eq(s3, 0)
    t.eq(select(2, util.robust_scale({})), 0)
  end)
end)
